    static final List<Tip> TIPS = List.of();

    record Tip(String group, List<String> patterns) {
        String key() {
            return "tip." + NAMESPACES.get(0) + "." + group;
        }

        String tag() {
            return NAMESPACES.get(0) + ".tip." + group;
        }

        boolean matches(Identifier id) {
            for (String pattern : patterns) {
                if (glob(pattern.contains(":") ? pattern : NAMESPACES.get(0) + ":" + pattern, id.toString())) return true;
            }
            return false;
        }
    }

