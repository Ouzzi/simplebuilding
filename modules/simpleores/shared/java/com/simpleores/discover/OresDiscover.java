    static final List<Tip> TIPS = List.of();

    record Tip(String group, List<String> patterns) {
        String key() {
            return "tip." + NAMESPACES.get(0) + "." + group;
        }

        String tag() {
            return NAMESPACES.get(0) + ".tip." + group;
        }

        boolean matches(Identifier id) {
            for (String pattern : patterns) {
                if (glob(pattern.contains(":") ? pattern : NAMESPACES.get(0) + ":" + pattern, id.toString())) return true;
            }
            return false;
        }
    }

    private OresDiscover() {
    }

    /** Vanilla inventory trigger of a server player (item picked up, crafted, moved in). */
    public static void onInventoryChanged(ServerPlayer player, ItemStack stack) {
        if (TIPS.isEmpty() || stack.isEmpty()) return;
        Tip tip = tipFor(stack);
        if (tip == null || player.entityTags().contains(tip.tag())) return;
        MinecraftServer server = player.level().getServer();
        show(player, tip, server == null ? null : server.getServerDirectory().resolve("config"));
    }

    /** Shows the tip unless it was seen or is switched off; true when it was shown now. */
    static boolean show(ServerPlayer player, Tip tip, Path configDir) {
        if (player.entityTags().contains(tip.tag()) || configDir != null && !tipsEnabled(configDir)) return false;
        if (!player.addTag(tip.tag())) return false;
        player.sendOverlayMessage(Component.translatable(tip.key()).withStyle(ChatFormatting.YELLOW));
        return true;
    }

    static Tip tipFor(ItemStack stack) {
        Identifier id = BuiltInRegistries.ITEM.getKey(stack.getItem());
        for (Tip tip : TIPS) {
            if (tip.matches(id)) return tip;
        }
        return null;
    }

    private static boolean tipsEnabled(Path configDir) {
        return com.simplebuilding.framework.api.FirstUseTips.firstPickupTips(configDir, MOD_ID);
    }

    private static boolean setTips(Path configDir, boolean enabled) throws Exception {
        com.simplebuilding.framework.api.FirstUseTips.set(configDir, MOD_ID, enabled);
        return true;
    }

    /** Every recipe of this mod that the recipe book can show has a recipe advancement that unlocks it. */
    public static void recipeUnlocks(GameTestHelper helper) {
        MinecraftServer server = helper.getLevel().getServer();
        Set<ResourceKey<Recipe<?>>> unlocked = new HashSet<>();
        for (AdvancementHolder advancement : server.getAdvancements().getAllAdvancements()) {
            unlocked.addAll(advancement.value().rewards().recipes());
        }
        List<String> missing = new ArrayList<>();
        for (RecipeHolder<?> holder : server.getRecipeManager().getRecipes()) {
            Identifier id = holder.id().identifier();
            Recipe<?> recipe = holder.value();
            if (!NAMESPACES.contains(id.getNamespace()) || recipe.isSpecial() || recipe.display().isEmpty()) continue;
            Identifier serializer = BuiltInRegistries.RECIPE_SERIALIZER.getKey(recipe.getSerializer());
            if (serializer != null && SECRET_SERIALIZERS.contains(serializer.toString())) continue;
            if (!unlocked.contains(holder.id())) missing.add(id.toString());
        }
        helper.assertTrue(missing.isEmpty(), MOD_ID + ": " + missing.size()
                + " recipes without recipe-book unlock (run tools/discover/discover.py): " + missing);
        helper.succeed();
    }

    /** Every item with an own behaviour class has a tooltip key or a wiki/guide entry. */
    public static void behaviourHints(GameTestHelper helper) {
        Map<String, String> lang = lang("en_us");
        List<String> missing = new ArrayList<>();
        for (Item item : BuiltInRegistries.ITEM) {
            Identifier id = BuiltInRegistries.ITEM.getKey(item);
            if (!NAMESPACES.contains(id.getNamespace())) continue;
            boolean own = own(item.getClass()) || item instanceof BlockItem block && own(block.getBlock().getClass());
            if (own && !documented(id) && !hasTooltip(lang, id.getPath())) missing.add(id.toString());
        }
        helper.assertTrue(missing.isEmpty(), MOD_ID + ": items with own behaviour but neither tooltip nor wiki/guide entry: "
                + missing);
        helper.succeed();
    }

    /** Every tip has EN/DE text and an item; a pickup shows it once, the switch keeps it off. */
    public static void firstPickupTips(GameTestHelper helper) {
        Map<String, String> en = lang("en_us");
        Map<String, String> de = lang("de_de");
        Item first = null;
        for (Tip tip : TIPS) {
            helper.assertTrue(en.containsKey(tip.key()) && de.containsKey(tip.key()), "no EN/DE text for " + tip.key());
            Item match = null;
            for (Item item : BuiltInRegistries.ITEM) {
                if (tip.matches(BuiltInRegistries.ITEM.getKey(item))) {
                    match = item;
                    break;
                }
            }
            helper.assertTrue(match != null, "tip " + tip.group() + " matches no registered item");
            if (first == null) first = match;
        }
        if (first == null) {
            helper.succeed();
            return;
        }
        ItemStack stack = new ItemStack(first);
        Tip tip = tipFor(stack);
        ServerPlayer player = helper.makeMockServerPlayerInLevel();
        try {
            Path off = Files.createTempDirectory("simple-tips");
            if (setTips(off, false)) {
                helper.assertTrue(!show(player, tip, off) && !player.entityTags().contains(tip.tag()),
                        "tip shown although switched off");
            }
        } catch (Exception e) {
            throw helper.assertionException("tip switch: " + e);
        }
        CriteriaTriggers.INVENTORY_CHANGED.trigger(player, player.getInventory(), stack);
        helper.assertTrue(player.entityTags().contains(tip.tag()), "picking up " + stack + " did not show " + tip.key());
        helper.assertTrue(!show(player, tip, null), "tip " + tip.key() + " shown twice");
        helper.succeed();
    }

    static boolean own(Class<?> type) {
        for (String prefix : OWN_PACKAGES) {
            if (type.getName().startsWith(prefix)) return true;
        }
        return false;
    }

    static boolean documented(Identifier id) {
        for (String pattern : DOCUMENTED) {
            if (glob(pattern, id.toString())) return true;
        }
        return false;
    }

    static boolean hasTooltip(Map<String, String> lang, String path) {
        for (String key : lang.keySet()) {
            if (key.contains("tooltip") && (key.contains("." + path + ".") || key.endsWith("." + path))) return true;
        }
        return false;
    }

    /** fnmatch like the wiki: {@code *}, {@code ?} and {@code [...]} classes. */
    static boolean glob(String pattern, String text) {
        StringBuilder regex = new StringBuilder();
        for (int i = 0; i < pattern.length(); i++) {
            char c = pattern.charAt(i);
            int close = c == '[' ? pattern.indexOf(']', i + 1) : -1;
            if (c == '*') {
                regex.append(".*");
            } else if (c == '?') {
                regex.append('.');
            } else if (close > i + 1) {
                regex.append('[').append(pattern, i + 1, close).append(']');
                i = close;
            } else {
                regex.append(Pattern.quote(String.valueOf(c)));
            }
        }
        return Pattern.matches(regex.toString(), text);
    }

    static Map<String, String> lang(String locale) {
        Map<String, String> out = new HashMap<>();
        String path = "/assets/" + NAMESPACES.get(0) + "/lang/" + locale + ".json";
        try (InputStream in = OresDiscover.class.getResourceAsStream(path)) {
            if (in == null) return out;
            for (Map.Entry<String, JsonElement> entry : JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8))
                    .getAsJsonObject().entrySet()) {
                out.put(entry.getKey(), entry.getValue().getAsString());
            }
        } catch (Exception e) {
            return out;
        }
        return out;
    }
