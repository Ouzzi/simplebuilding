package com.simplelib.api.client.ui;

/**
 * Engraved symbols of the container style (owner image 3: symbols instead of text), pixel art exactly as in
 * {@code tools/ui/simplecontainers_preview.py} ({@code #} = stroke). Drawn with {@link UiBoxes#symbol} and
 * {@link UiBoxes#symbolProgress}. Plain data, no client classes.
 */
public enum UiSymbol {
    /** Image 3's chunky arrow (furnace/crafting progress spot). */
    ARROW("..............#......", "..............##.....", "..............###....", "..............####...", "..............#####..", "###################..", "####################.", "#####################", "####################.", "###################..", "..............#####..", "..............####...", "..............###....", "..............##.....", "..............#......"),
    /** Small arrow (2x2 crafting). */
    ARROW_SMALL("..........#....", "..........##...", "..........###..", "#############..", "##############.", "###############", "##############.", "#############..", "..........###..", "..........##...", "..........#...."),
    /** Downward arrow (brewing progress). */
    ARROW_DOWN("...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "...###...", "#########", ".#######.", "..#####..", "..#####..", "...###...", "...###...", "....#....", "....#...."),
    /** Plus. */
    PLUS("....###....", "....###....", "....###....", "....###....", "###########", "###########", "###########", "....###....", "....###....", "....###....", "....###...."),
    /** Three rising heat waves (furnace, blast furnace). */
    HEAT(".#....#....#.", "#....#....#..", "#....#....#..", ".#....#....#.", "..#....#....#", "..#....#....#", ".#....#....#.", "#....#....#..", "#....#....#..", ".#....#....#.", "..#....#....#", "..#....#....#", ".#....#....#."),
    /** Soft smoke curls (smoker). */
    SMOKE("..##....##...", ".#..#..#..#..", "....#.....#..", "...#.....#...", "..#.....#....", "..#.....#.##.", "...#.....#..#", "....#......#.", "....#.....#..", "...#.....#...", "..#.....#....", "..#.....#....", "...#.....#..."),
    /** Cross (disabled crafter slot, invalid). */
    CROSS("#.....#", "##...##", ".##.##.", "..###..", ".##.##.", "##...##", "#.....#"),
    /** Check mark. */
    CHECK("......#", ".....##", "#...##.", "##.##..", ".###...", "..#...."),
    /** Grindstone wheel. */
    WHEEL("......#######......", "....##.......##....", "...#...........#...", "..#.....###.....#..", ".#....#######....#.", ".#...###...###...#.", "#...##.......##...#", "#...##..###..##...#", "#..##..#####..##..#", "#..##..#####..##..#", "#..##..#####..##..#", "#...##..###..##...#", "#...##.......##...#", ".#...###...###...#.", ".#....#######....#.", "..#.....###.....#..", "...#...........#...", "....##.......##....", "......#######......"),
    /** Open book (enchanting). */
    BOOK(".####.............####....", "#....###.........##...#...", "#.......##.....##......#..", "#.##......#.#.#..##....#..", "#...##.....#.#.....##..#..", "#.##........#.....##....#.", "#....###....#...##......#.", "#.##........#........##.#.", "#....##.....#......##...#.", "#.###.......#.....##.....#", "#......##...#...........#.", "#.##........#....###....#.", "##.....##...#.........###.", "..###.....#.#.#....###....", ".....####..###..###.......", ".........####.###........."),
    /** Filter funnel. */
    FUNNEL("############", "#..........#", ".#........#.", "..#......#..", "...#....#...", "....#..#....", "....#..#....", "....#..#....", "....#..#....", "....#..#....", ".....##....."),
    /** Stacked boxes. */
    STACK("..#####", "..#...#", "#####.#", "#...#.#", "#...###", "#...#..", "#####.."),
    /** Redstone dust blob (crafter power). */
    REDSTONE("....#..#....", ".#.###.##...", "..#####.#.#.", ".########...", "#.#######.#.", ".#########..", "..########.#", ".#.######...", "...##.###.#.", "..#..#.#....", ".....#......"),
    /** Hammer (anvil). */
    ANVIL_HAMMER(".#####", ".#####", ".#####", "...#..", "...#..", "...#..", "...#..", "...#.."),
    /** Experience orb. */
    XP("..###..", ".#####.", "###.###", "##...##", "###.###", ".#####.", "..###.."),
    /** Horseshoe (hoof slots). */
    HORSESHOE("...###...", "..#####..", ".##...##.", ".#.....#.", "#.......#", "#.......#", "#.......#", "#.......#");

    private final int[] xs, ys;
    private final int width, height;

    UiSymbol(String... rows) {
        int n = 0;
        for (String row : rows) for (char c : row.toCharArray()) if (c == '#') n++;
        xs = new int[n];
        ys = new int[n];
        int i = 0, w = 0;
        for (int y = 0; y < rows.length; y++) {
            for (int x = 0; x < rows[y].length(); x++) {
                if (rows[y].charAt(x) != '#') continue;
                xs[i] = x;
                ys[i++] = y;
                w = Math.max(w, x + 1);
            }
        }
        width = w;
        height = rows.length;
    }

    /** Width of the stroke area (rightmost stroke + 1). */
    public int width() {
        return width;
    }

    /** Height in rows. */
    public int height() {
        return height;
    }

    /** Number of stroke pixels. */
    public int size() {
        return xs.length;
    }

    /** X of stroke pixel {@code i}. */
    public int x(int i) {
        return xs[i];
    }

    /** Y of stroke pixel {@code i}. */
    public int y(int i) {
        return ys[i];
    }

    /** Whether {@code (x, y)} is a stroke pixel. */
    public boolean has(int x, int y) {
        for (int i = 0; i < xs.length; i++) if (xs[i] == x && ys[i] == y) return true;
        return false;
    }
}
