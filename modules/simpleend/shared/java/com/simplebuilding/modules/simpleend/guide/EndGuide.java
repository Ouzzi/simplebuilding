/**
 * The Simple End chapter of the Simple Modpack guide - GENERATED by tools/guides/module_guides.py from
 * tools/guides/ModuleGuide.java.in, do not edit (plans: docs/ai/PLAN-MODUL-GUIDES-2026-10-05.md, docs/ai/PLAN-B-GUIDE01-2026-11-03.md).
 *
 * <p>The pages ({@code simpleend.guide.page.<n>} and {@code .title}, {@link #PAGES} of them) are a chapter of SimpleLib's
 * Simple Modpack guide, handed in as data ({@code assets/simpleend/simplelib/modpack_guide.json}); the chapter opens with the
 * advancement {@link #CHAPTER} (holding {@link #RECIPE_ITEM}). The old single guide {@link #ID} stays registered so worlds
 * keep it: it leaves the creative tabs (SimpleLib's tab rules), has no recipe any more, and turns into the Simple Modpack
 * guide when used. Without SimpleLib it still opens as the Vanilla book it was. No SimpleLib class is used here.
 */
public final class EndGuide {
    public static final String NAMESPACE = "simpleend";
    public static final String AUTHOR = "Simple End";
    public static final int PAGES = 22;
    public static final Identifier ID = Identifier.fromNamespaceAndPath(NAMESPACE, "guide_book");
    /** The Simple Modpack guide (SimpleLib) the old book turns into. */
    public static final Identifier MODPACK_GUIDE = Identifier.fromNamespaceAndPath("simplelib", "modpack_guide");
    /** The chapter's unlock advancement and the Vanilla item it asks for (the old guide's recipe item). */
    public static final Identifier CHAPTER = Identifier.fromNamespaceAndPath(NAMESPACE, "guide/chapter");
    public static final Item RECIPE_ITEM = Items.CHORUS_FRUIT;
    /**
     * The chapter id in the guide data; the guide this book turns into carries it as {@code custom_data}
     * {@value #CHAPTER_TAG} (b-guidechap14: with SimpleLib's client switch it opens there).
     */
    public static final Identifier CHAPTER_ID = Identifier.fromNamespaceAndPath(NAMESPACE, "guide");
    public static final String CHAPTER_TAG = "simplelib_guide_chapter";
    private static Item book;

    private EndGuide() {
    }

    /** Registers the old book once; call from the loader's item registration. */
    public static Item register() {
        if (book == null) {
            Item.Properties properties = new Item.Properties().setId(ResourceKey.create(Registries.ITEM, ID)).stacksTo(1)
                    .component(DataComponents.WRITTEN_BOOK_CONTENT, content());
            book = Registry.register(BuiltInRegistries.ITEM, ID, new WrittenBookItem(properties) {
                @Override
                public InteractionResult use(Level level, Player player, InteractionHand hand) {
                    Item guide = BuiltInRegistries.ITEM.getOptional(MODPACK_GUIDE).orElse(null);
                    if (guide == null) return super.use(level, player, hand);
                    if (!level.isClientSide()) {
                        player.setItemInHand(hand, turned(guide));
                        level.playSound(null, player.blockPosition(), SoundEvents.BOOK_PAGE_TURN, SoundSource.PLAYERS, 1.0F, 1.0F);
                    }
                    return InteractionResult.SUCCESS;
                }
            });
        }
        return book;
    }

    /** The Simple Modpack guide this book turns into, marked with its chapter ({@link #CHAPTER_TAG}). */
    static ItemStack turned(Item guide) {
        ItemStack stack = new ItemStack(guide);
        CompoundTag tag = new CompoundTag();
        tag.putString(CHAPTER_TAG, CHAPTER_ID.toString());
        stack.set(DataComponents.CUSTOM_DATA, CustomData.of(tag));
        return stack;
    }

    /** The registered book; {@code null} before {@link #register}. */
    public static Item book() {
        return book;
    }

    public static ItemStack stack() {
        return new ItemStack(book);
    }

    public static Component page(int number) {
        String key = NAMESPACE + ".guide.page." + number;
        return Component.empty().append(Component.translatable(key + ".title").withStyle(ChatFormatting.BOLD))
                .append("\n\n").append(Component.translatable(key));
    }

    public static List<Component> pages() {
        List<Component> pages = new ArrayList<>();
        for (int i = 1; i <= PAGES; i++) {
            pages.add(page(i));
        }
        return pages;
    }

    public static WrittenBookContent content() {
        return new WrittenBookContent(Filterable.passThrough(""), AUTHOR, 0,
                pages().stream().map(Filterable::passThrough).toList(), true);
    }

    /**
     * Former start chapter: the single guides ship none any more (SimpleLib has the one start chapter), so this writes
     * nothing; kept for the loader adapters. Returns the number of files written, or -1 on failure.
     */
    public static int installQuests(Path configDir) {
        try {
            return ModuleQuestDefaults.install(configDir.resolve("ftbquests").resolve("quests"), NAMESPACE, EndGuide::questResource);
        } catch (IOException | RuntimeException e) {
            return -1;
        }
    }

    static String questResource(String relative) {
        return resource("/data/" + NAMESPACE + "/ftbquests/" + relative);
    }

    static String resource(String path) {
        try (InputStream in = EndGuide.class.getResourceAsStream(path)) {
            return in == null ? null : new String(in.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            return null;
        }
    }

    /**
     * GameTest (b-guide01): the Simple Modpack guide exists next to this mod alone, the old book has no recipe and turns
     * into it when used, the mod hands in its chapter as data, and the chapter's advancement opens with its item.
     */
    public static void gameTest(GameTestHelper h) {
        Item registered = BuiltInRegistries.ITEM.getValue(ID);
        h.assertTrue(registered instanceof WrittenBookItem && registered == book, "old guide book not registered: " + ID);
        Item guide = BuiltInRegistries.ITEM.getOptional(MODPACK_GUIDE).orElse(null);
        h.assertTrue(guide != null, "the Simple Modpack guide is missing - SimpleLib not bundled?");
        CraftingInput input = CraftingInput.of(2, 1, List.of(new ItemStack(Items.BOOK), new ItemStack(RECIPE_ITEM)));
        ItemStack crafted = h.getLevel().getServer().getRecipeManager().getRecipeFor(RecipeType.CRAFTING, input, h.getLevel())
                .map(recipe -> recipe.value().assemble(input)).orElse(ItemStack.EMPTY);
        h.assertTrue(!crafted.is(book), "the old guide recipe still exists");
        var player = h.makeMockServerPlayerInLevel();
        h.runBeforeTestEnd(() -> h.getLevel().getServer().getPlayerList().remove(player));
        player.setItemInHand(InteractionHand.MAIN_HAND, new ItemStack(book));
        h.assertTrue(player.getMainHandItem().use(h.getLevel(), player, InteractionHand.MAIN_HAND).consumesAction(), "the old guide does not react");
        h.assertTrue(player.getMainHandItem().is(guide), "using the old guide did not turn it into the Simple Modpack guide");
        var marked = player.getMainHandItem().get(DataComponents.CUSTOM_DATA);
        h.assertTrue(marked != null && CHAPTER_ID.toString().equals(marked.copyTag().getStringOr(CHAPTER_TAG, "")),
                "the turned guide does not remember its chapter " + CHAPTER_ID);
        String data = resource("/assets/" + NAMESPACE + "/simplelib/modpack_guide.json");
        h.assertTrue(data != null && data.contains("\"pages\": " + PAGES + ",") && data.contains("\"advancement\": \"" + CHAPTER + "\"")
                && data.contains("\"id\": \"" + CHAPTER_ID + "\""),
                "the chapter data for the Simple Modpack guide is missing or stale");
        var holder = h.getLevel().getServer().getAdvancements().get(CHAPTER);
        h.assertTrue(holder != null, "chapter advancement missing: " + CHAPTER);
        for (String criterion : holder.value().criteria().keySet()) player.getAdvancements().revoke(holder, criterion);
        h.assertTrue(!player.getAdvancements().getOrStartProgress(holder).isDone(), "the chapter is open before its item");
        ItemStack key = new ItemStack(RECIPE_ITEM);
        player.getInventory().add(key.copy());
        net.minecraft.advancements.triggers.CriteriaTriggers.INVENTORY_CHANGED.trigger(player, player.getInventory(), key);
        h.assertTrue(player.getAdvancements().getOrStartProgress(holder).isDone(), "picking up " + RECIPE_ITEM + " does not open the chapter");
        for (String locale : List.of("en_us", "de_de")) {
            String lang = resource("/assets/" + NAMESPACE + "/lang/" + locale + ".json");
            h.assertTrue(lang != null && lang.contains("\"" + NAMESPACE + ".guide.page." + PAGES + ".title\"")
                    && lang.contains("\"" + NAMESPACE + ".guide.chapter\"")
                    && !lang.contains("\"" + NAMESPACE + ".guide.page." + (PAGES + 1) + ".title\""), locale + " lacks the guide pages");
        }
        h.succeed();
    }
}
