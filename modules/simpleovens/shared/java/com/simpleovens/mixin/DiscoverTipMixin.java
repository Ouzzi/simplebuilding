package com.simpleovens.mixin;

import net.minecraft.advancements.triggers.InventoryChangeTrigger;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.entity.player.Inventory;
import net.minecraft.world.item.ItemStack;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

/**
 * First pickup tips (discoverability level H): the Vanilla inventory trigger runs whenever a server player's
 * inventory slot changes, so it sees every picked up, crafted or moved-in item. GENERATED by
 * tools/discover/discover.py from tools/discover/DiscoverTipMixin.java.in, do not edit.
 */
@Mixin(InventoryChangeTrigger.class)
public abstract class DiscoverTipMixin {
    @Inject(method = "trigger(Lnet/minecraft/server/level/ServerPlayer;Lnet/minecraft/world/entity/player/Inventory;Lnet/minecraft/world/item/ItemStack;)V", at = @At("HEAD"))
    private void discoverFirstPickupTip(ServerPlayer player, Inventory inventory, ItemStack stack, CallbackInfo ci) {
        com.simpleovens.discover.OvensDiscover.onInventoryChanged(player, stack);
    }
}
