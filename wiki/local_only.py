"""
N113: the pictures the wiki data names that exist only in a local generate run (wiki/data/local-only.js).

The wiki hosts are plain git trees. Every picture git ignores (Vanilla-derived textures, their sheet copies and
3D renders - AGENTS.md rule 7) is missing there unless the host fill step (wiki/vanilla_textures.py --derived, which
writes wiki/data/derived-present.json) put it there. The page reads this list and the host's present list
(assets/module-loader.js, WIKI_ASSET_OK) and does not ask for a picture that is not there - no 404, a text tile or the
"not published" box instead.

The list is every assets/textures/**.png the generated data files name (except the flat Vanilla textures under
assets/textures/minecraft/, which the page never asks the hosts for) that `git check-ignore` reports: it depends only
on the data and .gitignore, so the same commit gives the same file everywhere (a new texture before `git add` is not
ignored and so not listed - correct, it will be committed).
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

WIKI = Path(__file__).resolve().parent
TARGET = "data/local-only.js"
MARKER = "window.WIKI_LOCAL_ONLY = "
PICTURE = re.compile(r"assets/textures/[A-Za-z0-9_./-]+\.png")
SKIP_PREFIX = "assets/textures/minecraft/"


def data_files(wiki: Path = WIKI) -> list[Path]:
    """The generated data the page loads (module data, catalogue, books, textures, enchanting), not the Vanilla lines."""
    skip = {Path(TARGET).name}
    return sorted(p for p in (wiki / "data").glob("*.js") if p.name not in skip and not p.name.startswith("vanilla-"))


def referenced(wiki: Path = WIKI) -> set[str]:
    out: set[str] = set()
    for path in data_files(wiki):
        out.update(m for m in PICTURE.findall(path.read_text(encoding="utf-8")) if not m.startswith(SKIP_PREFIX))
    return out


def ignored(wiki: Path, paths: set[str]) -> set[str] | None:
    """The git-ignored ones (tracked files never count); None without git."""
    if not paths:
        return set()
    try:
        done = subprocess.run(["git", "-C", str(wiki), "check-ignore", "--stdin"], input="\n".join(sorted(paths)) + "\n",
                              capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.SubprocessError):
        return None
    if done.returncode not in (0, 1):  # 1 = nothing ignored
        return None
    return {line.strip() for line in done.stdout.splitlines() if line.strip()}


def build(wiki: Path = WIKI) -> dict[str, list[str]] | None:
    """{folder/: [file names without .png]} - grouped, so the list stays small."""
    paths = ignored(wiki, referenced(wiki))
    if paths is None:
        return None
    grouped: dict[str, list[str]] = {}
    for p in sorted(paths):
        folder, name = p.rsplit("/", 1)
        grouped.setdefault(folder + "/", []).append(name[:-4])
    return grouped


def render(grouped: dict[str, list[str]]) -> str:
    lines = [json.dumps(k) + ": " + json.dumps(v, separators=(",", ":")) for k, v in sorted(grouped.items())]
    return ("// Generated by wiki/generate.py (wiki/local_only.py) - do not edit.\n"
            "// Pictures the wiki data names that git ignores (Vanilla-derived): on the hosts only if the fill step wrote them.\n"
            + MARKER + "{\n" + ",\n".join(lines) + "\n};\n")


def read(wiki: Path = WIKI) -> dict[str, list[str]] | None:
    try:
        text = (wiki / TARGET).read_text(encoding="utf-8")
        return json.loads(text.split(MARKER, 1)[1].rstrip().rstrip(";"))
    except (OSError, ValueError, IndexError):
        return None


def flat(grouped: dict[str, list[str]] | None) -> set[str]:
    return {folder + name + ".png" for folder, names in (grouped or {}).items() for name in names}


def sync(wiki: Path = WIKI, check: bool = False) -> list[str]:
    grouped = build(wiki)
    if grouped is None:
        return []  # no git (exported tree): leave the committed list alone
    if check:
        if read(wiki) != grouped:
            return [f"wiki/{TARGET} is out of date with the wiki data - run python wiki/generate.py"]
        return []
    text = render(grouped)
    target = wiki / TARGET
    if not target.exists() or target.read_text(encoding="utf-8") != text:
        target.write_text(text, encoding="utf-8", newline="\n")
    return []


if __name__ == "__main__":
    import sys
    problems = sync(check="--check" in sys.argv)
    for problem in problems:
        print("PROBLEM:", problem)
    if not problems and "--check" not in sys.argv:
        print(f"wiki/{TARGET}: {len(flat(read()))} pictures")
    sys.exit(1 if problems else 0)
